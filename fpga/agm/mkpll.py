#!/usr/bin/env python3
"""Write NetGD's Audio_PLL wrapper for the AG16K from the PLL settings Supra computed.

usage: mkpll.py <Audio_PLL_PLLVE.v made by pll.tcl> <out: Audio_PLL.v>

The output has the same module name and ports as the Quartus altpll wrapper of
the v5.5 build (inclk0 -> c0), so fpga/agm/src/OpenGDEMU.v instantiates it
unchanged. Only the `defparam` values are taken from Supra's file; they are
numbers Supra computed for 11.2896 MHz -> 33.8688 MHz and are not checked in
(the generated wrapper lives in the work directory).

Unverified on hardware: that feedback through clkfbout is the right hookup for
fb_mode 0, that the PLL locks, that the VCO frequency is in range.
"""
import re
import sys

src, dst = sys.argv[1:3]
text = open(src).read()
if not re.search(r"^\s*alta_pllve\s+\w+\s*\(", text, re.M):
    sys.exit("mkpll.py: %s does not instantiate alta_pllve" % src)
params = re.findall(r"^\s*defparam\s+\w+\.(\w+)\s*=\s*([^;]+);", text, re.M)
names = [n for n, _ in params]
for need in ("CLKFB_HIGH", "CLKFB_LOW", "CLKOUT0_HIGH", "CLKOUT0_LOW", "CLKDIV0_EN", "FEEDBACK_MODE"):
    if need not in names:
        sys.exit("mkpll.py: %s has no %s parameter" % (src, need))
if len(set(names)) != len(names):
    sys.exit("mkpll.py: duplicate defparam in %s" % src)

out = [
    "// GENERATED by fpga/agm/mkpll.py -- do not edit, do not check in.",
    "// Audio_PLL for the AG16K: 11.2896 MHz -> 33.8688 MHz, alta_pllve.",
    "// Parameter values: Supra `generate_pll ... -pll_type PLLVE -input_freq 11.2896",
    "// -output_freqs 33.8688 -fb_mode 0` (see pll.tcl).",
    "module Audio_PLL (",
    "   input  inclk0,",
    "   output c0",
    ");",
    "   wire fb;",
    "   alta_pllve pll (",
    "      .clkin(inclk0), .clkfb(fb), .pfden(1'b1), .resetn(1'b1),",
    "      .phasecounterselect(3'b000), .phaseupdown(1'b0), .phasestep(1'b0),",
    "      .scanclk(1'b0), .scanclkena(1'b0), .scandata(1'b0), .configupdate(1'b0),",
    "      .clkout0(c0), .clkout1(), .clkout2(), .clkout3(), .clkout4(),",
    "      .clkfbout(fb), .lock(), .scandataout(), .scandone(), .phasedone()",
    "   );",
    '   defparam pll.CLKIN_FREQ = "11.2896";',
]
out += ["   defparam pll.%s = %s;" % (n, v.strip()) for n, v in params]
out.append("endmodule")
open(dst, "w", newline="\n").write("\n".join(out) + "\n")
print("mkpll.py: %d parameters -> %s" % (len(params), dst))
