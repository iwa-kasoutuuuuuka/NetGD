#!/usr/bin/env python3
"""Turn fwmsg.def into fwmsg_gen.h.   python gen_msgs.py [--check]

Each message becomes   FWMSG(FWM_<ID>, "english", "japanese (UTF-8)", "japanese (EUC-JP)")
with every non-ASCII byte written as a 3-digit octal escape, so the C sources stay ASCII.
EUC-JP is what the BIOS font draws once bfont_set_encoding(BFONT_CODE_EUC) is set.
--check: exit 1 if fwmsg_gen.h is not what the def file produces (the host tests use it).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def c_escape(raw):
    out = []
    for b in raw:
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif b == 0x0A:
            out.append("\\n")
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return "".join(out)


def generate(def_path):
    lines = ["/* Generated by gen_msgs.py from fwmsg.def. Do not edit. */"]
    seen = set()
    with open(def_path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\r\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = [p.strip() for p in line.split("|")]
            if len(parts) != 3 or not all(parts):
                raise SystemExit("%s:%d: expected 'ID | English | Japanese'" % (def_path, n))
            mid, en, ja = parts
            if mid in seen:
                raise SystemExit("%s:%d: duplicate id %s" % (def_path, n, mid))
            seen.add(mid)
            if not en.isascii():
                raise SystemExit("%s:%d: the English text must be ASCII" % (def_path, n))
            en = en.replace("\\n", "\n")
            ja = ja.replace("\\n", "\n")
            try:
                euc = ja.encode("euc_jp")
            except UnicodeEncodeError as e:
                raise SystemExit("%s:%d: not encodable as EUC-JP: %s" % (def_path, n, e))
            lines.append('FWMSG(FWM_%s, "%s", "%s", "%s")' % (
                mid, c_escape(en.encode("ascii")), c_escape(ja.encode("utf-8")), c_escape(euc)))
    return "\n".join(lines) + "\n"


def main(argv):
    def_path = os.path.join(HERE, "fwmsg.def")
    out_path = os.path.join(HERE, "fwmsg_gen.h")
    text = generate(def_path)
    if "--check" in argv:
        try:
            with open(out_path, encoding="ascii", newline="") as f:
                cur = f.read()
        except OSError:
            cur = None
        if cur != text:
            print("fwmsg_gen.h is out of date: run python gen_msgs.py", file=sys.stderr)
            return 1
        return 0
    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d messages)" % (out_path, text.count("\nFWMSG(")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
