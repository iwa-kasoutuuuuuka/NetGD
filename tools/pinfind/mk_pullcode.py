#!/usr/bin/env python3
"""Generate the 10 weak-pull-up code variants of the EP2C5F256C8 stage-0.

usage: mk_pullcode.py [--padmap tools/pinfind/ep2c5_padmap.csv]
                      [--code tools/pinfind/ep2c5_pullcode.csv]
                      [--out fpga/pullcode-ep2c5]

Every user I/O ball and every dedicated clock-input ball of the F256
package (taken from ep2c5_padmap.csv: the balls whose I/O Type is Row I/O
or Column I/O) becomes an input port p_<BALL>. There are no outputs or
bidirs. The configuration / JTAG / dedicated balls (I/O Type "--") and the
supply / NC balls are not ports.

Each coded ball gets a distinct 10-bit codeword with exactly 5 ones
(constant-weight code, C(10,5) = 252 words). Balls are taken in pad order;
each one gets, among the unused words, the one that keeps the per-bit
counts most even (ties: lowest word in itertools.combinations order), so
every variant pulls up about half of the coded balls. Variant k sets
WEAK_PULL_UP_RESISTOR ON exactly on the balls whose codeword bit k is 1
and OFF on every other port. Bus hold is OFF on every port. Everything else
is the stage-0 qsf (fpga/stage0-ep2c5/stage0.qsf).

Dedicated clock-input balls: see CLOCK_PULLUP below.

Writes:
  <code>                     ball,pad,bank,io_type,kind,in_code,code,note
  <out>/pullcode.qpf
  <out>/pullcode.v           one input port per ball, no logic
  <out>/k<k>/pullcode.qsf    k = 0..9

Standard library only. The output is deterministic.
"""
import argparse
import csv
import itertools
import os
import re
import sys

NBITS = 10
WEIGHT = 5
# Cyclone II dedicated clock inputs (CLK0..CLK7 = F256 H1 H2 J1 J2 H15 H16
# J15 J16; listed as GND+ when unused) have no weak pull-up. With them coded
# (CI run 45824026037) Quartus II 13.0 SP1 stopped every variant with
# "Error (169057): Can't place I/O pin p_<ball> ... I/O pin uses weak
# pullup, which is not supported by this pin location" on exactly the
# clock balls whose bit was 1. So they stay input ports with pull-up OFF
# and carry no codeword (docs/research/ep2c5-pullcode.md).
CLOCK_PULLUP = False

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))


def load_ports(padmap):
    """Return [(ball, pad, bank, io_type, kind)] sorted by pad number."""
    out = []
    with open(padmap, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            ball = r["f256_ball"]
            if not ball or r["io_type"] not in ("Row I/O", "Column I/O"):
                continue
            kind = "clock" if "clock input" in r["special"] else "io"
            out.append((ball, int(r["pad"]), r["bank"], r["io_type"], kind))
    out.sort(key=lambda x: x[1])
    return out


def assign_codes(n):
    """n distinct weight-5 words (strings of '0'/'1', bit k at index k)."""
    words = ["".join("1" if i in c else "0" for i in range(NBITS))
             for c in itertools.combinations(range(NBITS), WEIGHT)]
    if n > len(words):
        raise SystemExit(f"{n} balls but only {len(words)} codewords")
    used = set()
    count = [0] * NBITS
    out = []
    for _ in range(n):
        best = None
        for w in words:
            if w in used:
                continue
            c = [count[i] + (w[i] == "1") for i in range(NBITS)]
            key = (max(c) - min(c), max(c))
            if best is None or key < best[0]:
                best = (key, w)
        w = best[1]
        used.add(w)
        for i in range(NBITS):
            count[i] += w[i] == "1"
        out.append(w)
    return out


def port(ball):
    return "p_" + ball


def stage0_globals():
    """Global assignments of the stage-0 qsf, minus its single pin."""
    p = os.path.join(ROOT, "fpga", "stage0-ep2c5", "stage0.qsf")
    keep = []
    with open(p, encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if not s.startswith("set_global_assignment"):
                continue
            if re.search(r"-name (TOP_LEVEL_ENTITY|VERILOG_FILE)\b", s):
                continue
            keep.append(s)
    return keep


def qsf_text(k, rows):
    on = sum(1 for r in rows if r["code"] and r["code"][k] == "1")
    L = [
        f"# GENERATED by tools/pinfind/mk_pullcode.py -- do not edit.",
        f"# EP2C5F256C8 weak pull-up code variant k={k} (Quartus II 13.0 SP1).",
        "#",
        "# Every user I/O and clock-input ball is an input port; no outputs,",
        "# no bidirs, no logic. WEAK_PULL_UP_RESISTOR is ON exactly on the",
        f"# balls whose codeword bit {k} is 1 ({on} balls), OFF on the rest.",
        "# Bus hold OFF everywhere. All other settings are the stage-0 ones",
        "# (fpga/stage0-ep2c5/stage0.qsf). tools/pinfind/ep2c5gate.py --pullcode",
        f"# {k} checks the fitter's result. Bitstreams are CI artifacts only.",
        "",
        "set_global_assignment -name TOP_LEVEL_ENTITY pullcode",
        "set_global_assignment -name VERILOG_FILE pullcode.v",
    ]
    L += stage0_globals()
    L.append("")
    for r in rows:
        p = port(r["ball"])
        pu = "ON" if r["code"] and r["code"][k] == "1" else "OFF"
        L.append(f"set_location_assignment PIN_{r['ball']} -to {p}")
        L.append(f"set_instance_assignment -name IO_STANDARD \"3.3-V LVTTL\" -to {p}")
        L.append(f"set_instance_assignment -name WEAK_PULL_UP_RESISTOR {pu} -to {p}")
        L.append(f"set_instance_assignment -name ENABLE_BUS_HOLD_CIRCUITRY OFF -to {p}")
    L.append("")
    return "\n".join(L)


def verilog_text(rows):
    L = [
        "// GENERATED by tools/pinfind/mk_pullcode.py -- do not edit.",
        "// EP2C5F256C8 weak pull-up code design: one input port per user I/O",
        "// and clock-input ball, NO outputs or bidirs, no logic. The weak",
        "// pull-ups are set per variant in k<k>/pullcode.qsf.",
        "module pullcode (",
    ]
    for i, r in enumerate(rows):
        sep = "," if i + 1 < len(rows) else ""
        L.append(f"    input wire {port(r['ball'])}{sep}")
    L += [");", "endmodule", ""]
    return "\n".join(L)


def build(padmap, clock_pullup=CLOCK_PULLUP):
    ports = load_ports(padmap)
    coded = [p for p in ports if clock_pullup or p[4] != "clock"]
    codes = dict(zip((p[0] for p in coded), assign_codes(len(coded))))
    rows = []
    for ball, pad, bank, iot, kind in ports:
        code = codes.get(ball, "")
        note = ""
        if not code:
            note = "dedicated clock input: no programmable weak pull-up; port with pull-up OFF"
        rows.append({"ball": ball, "pad": str(pad), "bank": bank, "io_type": iot,
                     "kind": kind, "in_code": "yes" if code else "no",
                     "code": code, "note": note})
    return rows


CODE_COLS = ["ball", "pad", "bank", "io_type", "kind", "in_code", "code", "note"]


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--padmap", default=os.path.join(HERE, "ep2c5_padmap.csv"))
    ap.add_argument("--code", default=os.path.join(HERE, "ep2c5_pullcode.csv"))
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "pullcode-ep2c5"))
    a = ap.parse_args(argv)
    rows = build(a.padmap)
    os.makedirs(os.path.dirname(os.path.abspath(a.code)), exist_ok=True)
    with open(a.code, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=CODE_COLS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    write(os.path.join(a.out, "pullcode.qpf"),
          'QUARTUS_VERSION = "13.0"\nPROJECT_REVISION = "pullcode"\n')
    write(os.path.join(a.out, "pullcode.v"), verilog_text(rows))
    for k in range(NBITS):
        write(os.path.join(a.out, f"k{k}", "pullcode.qsf"), qsf_text(k, rows))
    coded = [r for r in rows if r["code"]]
    per = [sum(r["code"][k] == "1" for r in coded) for k in range(NBITS)]
    print(f"ports {len(rows)}; coded {len(coded)}; "
          f"excluded {len(rows) - len(coded)}; pull-ups per variant {per}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
