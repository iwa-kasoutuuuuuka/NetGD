#!/usr/bin/env python3
"""Generate the EP2C5F256C8 scan2 core wrapper and its three I/O variants
(fpga/scan2-ep2c5, Run A of docs/research/ag16k-ps-plan-run4.md).

usage: mk_scan2.py [--padmap tools/pinfind/ep2c5_padmap.csv]
                   [--tables tools/pinfind] [--out fpga/scan2-ep2c5]

The ports, directions and the raw / DC / clock numbering are exactly those
of the scan core (mk_scan.build): outputs only on the 16 MCU_DATA balls,
every other user I/O and clock ball an input, no PLL, stage-0 options.
The three variants differ only in the weak pull-up / bus hold of a listed
set of input balls:

  v0  as scan: weak pull-up ON on every user I/O input, OFF on the 8 clock
      balls and the 16 MCU_DATA outputs; bus hold OFF everywhere.
  v1  as v0, but weak pull-up OFF on the 33 DC_* balls and on C4 / C5
      (B4's unassigned neighbours).
  v2  as v0, but on the 33 DC_* balls: weak pull-up OFF, bus hold ON.

Writes:
  <tables>/ep2c5_scan2_v{0,1,2}.csv   mk_scan.COLS + bushold
  <out>/scan2.qpf
  <out>/scan2.v                       port wrapper around scan2_core
  <out>/scan2_v{0,1,2}.qsf            CI copies the variant to scan2.qsf
scan2_core.v, g1x.v and scan2.sdc are hand-written; scan_core.v is used
from fpga/scan-ep2c5 unchanged.

Standard library only. The output is deterministic.
"""
import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)

import mk_scan  # noqa: E402

VARIANTS = (0, 1, 2)
# B4's unassigned F256 neighbours that v1 also releases (plan 2.2).
V1_EXTRA = ("C4", "C5")
# Control ball of measurement (a): an unassigned neighbour of B4.
CTRL_BALL = "C4"
COLS = mk_scan.COLS + ["bushold"]
VERILOG_FILES = ("scan2.v", "scan2_core.v", "g1x.v", "scan_core.v")


def dc_balls(rows):
    return {r["ball"] for r in rows if r["dc"] != ""}


def variant_set(rows, k):
    """Balls whose I/O setting differs from v0 in variant k."""
    if k == 0:
        return set()
    if k == 1:
        return dc_balls(rows) | set(V1_EXTRA)
    if k == 2:
        return dc_balls(rows)
    raise ValueError(k)


def build(padmap, k):
    rows = []
    for r in mk_scan.build(padmap):
        r = dict(r)
        r["bushold"] = "off"
        rows.append(r)
    tab = {r["ball"]: r for r in rows}
    for b in V1_EXTRA:
        if tab[b]["signal"] or tab[b]["dir"] != "input" or tab[b]["kind"] != "io":
            raise SystemExit(f"mk_scan2: {b} is not an unassigned input")
    for b in variant_set(rows, k):
        r = tab[b]
        if r["dir"] != "input" or r["kind"] != "io":
            raise SystemExit(f"mk_scan2: variant ball {b} is not an I/O input")
        r["pullup"] = "off"
        if k == 2:
            r["bushold"] = "on"
    return rows


def verilog_text(rows):
    t = mk_scan.verilog_text(rows)
    reps = [
        ("// GENERATED by tools/pinfind/mk_scan.py -- do not edit.\n"
         "// EP2C5F256C8 scan core: port wrapper.",
         "// GENERATED by tools/pinfind/mk_scan2.py -- do not edit.\n"
         "// EP2C5F256C8 scan2 core: port wrapper (identical ports to scan.v)."),
        ("The logic is in scan_core.v; the address map is\n"
         "// docs/research/ep2c5-scan.md.",
         "The logic is in scan2_core.v; the address map is\n"
         "// docs/research/ep2c5-scan2.md."),
        ("module scan (", "module scan2 ("),
        ("    scan_core core (\n"
         "        .raw(raw), .clk(clk), .dc(dc), .addr(addr),",
         "    scan2_core core (\n"
         f"        .raw(raw), .clk(clk), .dc(dc), .c4({mk_scan.port(CTRL_BALL)}), .addr(addr),"),
    ]
    for a, b in reps:
        if t.count(a) != 1:
            raise SystemExit(f"mk_scan2: wrapper template changed: {a[:40]!r}")
        t = t.replace(a, b)
    return t


def qsf_text(rows, k):
    n_on = sum(r["pullup"] == "on" for r in rows)
    n_bh = sum(r["bushold"] == "on" for r in rows)
    desc = {
        0: "v0: as scan (weak pull-up ON on every user I/O input).",
        1: "v1: weak pull-up OFF on the 33 DC_* balls and C4 / C5.",
        2: "v2: bus hold ON, weak pull-up OFF on the 33 DC_* balls.",
    }[k]
    L = [
        "# GENERATED by tools/pinfind/mk_scan2.py -- do not edit.",
        f"# EP2C5F256C8 scan2 core, variant {desc}",
        "# (Quartus II 13.0 SP1; CI copies this file to scan2.qsf.)",
        "#",
        "# Outputs (tri-state) only on the 16 MCU_DATA balls (pull-up OFF);",
        f"# every other port is an input: weak pull-up ON on {n_on} balls,",
        f"# bus hold ON on {n_bh} balls. No PLL. All other settings are the",
        "# stage-0 ones (fpga/stage0-ep2c5/stage0.qsf).",
        f"# tools/pinfind/ep2c5gate.py --scan2 {k} checks the fitter's result.",
        "# Bitstreams are CI artifacts only.",
        "",
        "set_global_assignment -name TOP_LEVEL_ENTITY scan2",
    ]
    L += [f"set_global_assignment -name VERILOG_FILE {f}" for f in VERILOG_FILES]
    L.append("set_global_assignment -name SDC_FILE scan2.sdc")
    L += mk_scan.stage0_globals()
    L.append("")
    for r in rows:
        p = mk_scan.port(r["ball"])
        L.append(f"set_location_assignment PIN_{r['ball']} -to {p}")
        L.append(f"set_instance_assignment -name IO_STANDARD \"3.3-V LVTTL\" -to {p}")
        L.append(f"set_instance_assignment -name WEAK_PULL_UP_RESISTOR "
                 f"{'ON' if r['pullup'] == 'on' else 'OFF'} -to {p}")
        L.append(f"set_instance_assignment -name ENABLE_BUS_HOLD_CIRCUITRY "
                 f"{'ON' if r['bushold'] == 'on' else 'OFF'} -to {p}")
    L.append("")
    return "\n".join(L)


def table_path(tables, k):
    return os.path.join(tables, f"ep2c5_scan2_v{k}.csv")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--padmap", default=os.path.join(HERE, "ep2c5_padmap.csv"))
    ap.add_argument("--tables", default=HERE)
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "scan2-ep2c5"))
    a = ap.parse_args(argv)
    for k in VARIANTS:
        rows = build(a.padmap, k)
        with open(table_path(a.tables, k), "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=COLS, lineterminator="\n")
            w.writeheader()
            w.writerows(rows)
        mk_scan.write(os.path.join(a.out, f"scan2_v{k}.qsf"), qsf_text(rows, k))
        print(f"v{k}: ports {len(rows)}; outputs {sum(r['dir'] == 'output' for r in rows)}; "
              f"pull-up on {sum(r['pullup'] == 'on' for r in rows)}; "
              f"bus hold on {sum(r['bushold'] == 'on' for r in rows)}")
    rows = build(a.padmap, 0)
    mk_scan.write(os.path.join(a.out, "scan2.qpf"),
                  'QUARTUS_VERSION = "13.0"\nPROJECT_REVISION = "scan2"\n')
    mk_scan.write(os.path.join(a.out, "scan2.v"), verilog_text(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
